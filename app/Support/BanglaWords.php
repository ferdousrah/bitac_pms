<?php

namespace App\Support;

/**
 * An amount of taka in Bangla words, the way BITAC writes it on a receipt:
 * 7800 → "সাত হাজার আটশত টাকা মাত্র", 125000.50 → "এক লক্ষ পঁচিশ হাজার টাকা পঞ্চাশ পয়সা মাত্র".
 * Counted in the subcontinent's units — হাজার, লক্ষ, কোটি.
 */
class BanglaWords
{
    /** 1–99 — Bangla numbers below a hundred are each their own word. */
    private const UPTO_99 = [
        '', 'এক', 'দুই', 'তিন', 'চার', 'পাঁচ', 'ছয়', 'সাত', 'আট', 'নয়', 'দশ',
        'এগারো', 'বারো', 'তেরো', 'চৌদ্দ', 'পনেরো', 'ষোল', 'সতেরো', 'আঠারো', 'উনিশ', 'বিশ',
        'একুশ', 'বাইশ', 'তেইশ', 'চব্বিশ', 'পঁচিশ', 'ছাব্বিশ', 'সাতাশ', 'আটাশ', 'ঊনত্রিশ', 'ত্রিশ',
        'একত্রিশ', 'বত্রিশ', 'তেত্রিশ', 'চৌত্রিশ', 'পঁয়ত্রিশ', 'ছত্রিশ', 'সাঁইত্রিশ', 'আটত্রিশ', 'ঊনচল্লিশ', 'চল্লিশ',
        'একচল্লিশ', 'বিয়াল্লিশ', 'তেতাল্লিশ', 'চুয়াল্লিশ', 'পঁয়তাল্লিশ', 'ছেচল্লিশ', 'সাতচল্লিশ', 'আটচল্লিশ', 'ঊনপঞ্চাশ', 'পঞ্চাশ',
        'একান্ন', 'বাহান্ন', 'তিপ্পান্ন', 'চুয়ান্ন', 'পঞ্চান্ন', 'ছাপ্পান্ন', 'সাতান্ন', 'আটান্ন', 'ঊনষাট', 'ষাট',
        'একষট্টি', 'বাষট্টি', 'তেষট্টি', 'চৌষট্টি', 'পঁয়ষট্টি', 'ছেষট্টি', 'সাতষট্টি', 'আটষট্টি', 'ঊনসত্তর', 'সত্তর',
        'একাত্তর', 'বাহাত্তর', 'তিয়াত্তর', 'চুয়াত্তর', 'পঁচাত্তর', 'ছিয়াত্তর', 'সাতাত্তর', 'আটাত্তর', 'ঊনআশি', 'আশি',
        'একাশি', 'বিরাশি', 'তিরাশি', 'চুরাশি', 'পঁচাশি', 'ছিয়াশি', 'সাতাশি', 'আটাশি', 'ঊননব্বই', 'নব্বই',
        'একানব্বই', 'বিরানব্বই', 'তিরানব্বই', 'চুরানব্বই', 'পঁচানব্বই', 'ছিয়ানব্বই', 'সাতানব্বই', 'আটানব্বই', 'নিরানব্বই',
    ];

    /** A whole number in words; zero is "শূন্য". */
    public static function number(int $n): string
    {
        if ($n === 0) return 'শূন্য';

        $parts = [];
        foreach ([[10000000, 'কোটি'], [100000, 'লক্ষ'], [1000, 'হাজার']] as [$unit, $word]) {
            if ($n >= $unit) {
                // More than 99 crore reads as "একশত কোটি" etc.
                $parts[] = self::number(intdiv($n, $unit)) . ' ' . $word;
                $n %= $unit;
            }
        }
        if ($n >= 100) {
            $parts[] = self::UPTO_99[intdiv($n, 100)] . 'শত';
            $n %= 100;
        }
        if ($n > 0) $parts[] = self::UPTO_99[$n];

        return implode(' ', $parts);
    }

    /** "… টাকা [… পয়সা] মাত্র". */
    public static function taka(float $amount): string
    {
        $paisa = (int) round($amount * 100);
        $taka  = intdiv($paisa, 100);
        $paisa %= 100;

        return self::number($taka) . ' টাকা' . ($paisa ? ' ' . self::number($paisa) . ' পয়সা' : '') . ' মাত্র';
    }
}
